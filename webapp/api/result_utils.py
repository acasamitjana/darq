def _json_value(value):
    """Convert a pandas / NumPy scalar into a JSON-safe value."""
    if pd.isna(value):
        return None
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return round(float(value), 4)
    return value


def _dataframe_payload(df: pd.DataFrame) -> dict:
    """Return a stable JSON representation while preserving table column order."""
    display_df = _format_df_for_display(df)
    columns = [str(column) for column in display_df.columns]
    rows = [
        [_json_value(value) for value in row]
        for row in display_df.itertuples(index=False, name=None)
    ]
    return {
        "columns": columns,
        "rows": rows,
    }


def prepare_job_results(job_dir: Path, meta: dict) -> dict:
    """Prepare the exact same DARQ tables, overlay panel and PDF used by Gradio."""
    input_dir = job_dir / "input"
    output_dir = job_dir / "output"

    dat_path = input_dir / "dat.nii.gz"
    mri_path = input_dir / "mri.nii.gz"

    if not output_dir.exists():
        raise FileNotFoundError(f"Output folder not found for job: {meta.get('job_id', job_dir.name)}")

    sbr_raw = _read_first_tsv(output_dir, "*_sbr.tsv")
    symm_raw = _read_first_tsv(output_dir, "*_symm.tsv")

    if sbr_raw.empty:
        raise FileNotFoundError(f"No SBR table was found in: {output_dir}")

    if symm_raw.empty:
        raise FileNotFoundError(f"No symmetry table was found in: {output_dir}")

    display_dir = job_dir / "display"
    display_dir.mkdir(exist_ok=True)

    overlay_panel_path = display_dir / "overlay_panel.png"
    overlay_gallery = []

    expected_gallery = [
        display_dir / "overlay_axial.png",
        display_dir / "overlay_coronal.png",
        display_dir / "overlay_sagittal.png",
    ]

    if not all(path.exists() for path in expected_gallery):
        overlay_gallery = _create_overlay_gallery(
            mri_path=mri_path,
            output_dir=output_dir,
            run_dir=job_dir,
        )
    else:
        overlay_gallery = [
            (str(expected_gallery[0]), "Axial"),
            (str(expected_gallery[1]), "Coronal"),
            (str(expected_gallery[2]), "Sagittal"),
        ]

    if not overlay_panel_path.exists():
        generated_panel = _create_overlay_panel(
            mri_path=mri_path,
            output_dir=output_dir,
            run_dir=job_dir,
        )
        if generated_panel is None:
            raise FileNotFoundError("DARQ overlay panel could not be generated.")

    pipeline_log_path = job_dir / "logs" / "pipeline.log"
    if pipeline_log_path.exists():
        pipeline_log = pipeline_log_path.read_text(
            encoding="utf-8",
            errors="ignore",
        )
    else:
        pipeline_log = "Pipeline log not found."

    completed = subprocess.CompletedProcess(
        args=["real_worker"],
        returncode=0,
        stdout=pipeline_log,
        stderr="",
    )

    status_text = _status_text(
        completed=completed,
        output_dir=output_dir,
        sbr_raw=sbr_raw,
        symm_raw=symm_raw,
    )

    subject_id = meta.get("subject_id") or meta.get("job_id") or job_dir.name
    pdf_path = job_dir / "DARQ_report.pdf"
    report_style_marker = display_dir / "report_style_version.txt"

    current_style_version = (
        report_style_marker.read_text(encoding="utf-8").strip()
        if report_style_marker.exists()
        else ""
    )

    # Regenerate an existing report once when the visual report style changes.
    # This lets completed jobs receive the new layout without touching any DARQ
    # processing output, biomarker value, image, worker or job metadata.
    if not pdf_path.exists() or current_style_version != REPORT_STYLE_VERSION:
        generated_pdf = _create_pdf_report(
            run_dir=job_dir,
            subject_id=subject_id,
            dat_input_path=dat_path,
            mri_input_path=mri_path,
            raw_sbr=sbr_raw,
            raw_symm=symm_raw,
            overlay_gallery=overlay_gallery,
            completed=completed,
            status_text=status_text,
        )
        if generated_pdf is None:
            raise RuntimeError("DARQ PDF report could not be generated.")
        pdf_path = generated_pdf
        report_style_marker.write_text(
            REPORT_STYLE_VERSION,
            encoding="utf-8",
        )

    job_id = meta.get("job_id", job_dir.name)

    return {
        "job_id": job_id,
        "subject_id": subject_id,
        "sbr": _dataframe_payload(sbr_raw),
        "symmetry": _dataframe_payload(symm_raw),
        "overlay_url": f"/api/jobs/{job_id}/overlay-panel",
        "pdf_url": f"/api/jobs/{job_id}/report",
        "overlay_path": overlay_panel_path,
        "pdf_path": Path(pdf_path),
    }
