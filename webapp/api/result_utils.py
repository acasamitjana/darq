def _read_first_tsv(output_dir: Path, pattern: str) -> pd.DataFrame:
    """Read the first TSV matching a pattern, or return an empty table."""
    matches = sorted(output_dir.glob(pattern))
    if not matches:
        return pd.DataFrame()
    return pd.read_csv(matches[0], sep="\t")

def _format_number(value, digits: int = 4) -> str:
    """Format numbers for report tables without changing the underlying values."""
    try:
        if pd.isna(value):
            return "—"
        if isinstance(value, (float, np.floating)):
            return f"{float(value):.{digits}f}"
        if isinstance(value, (int, np.integer)):
            return str(int(value))
    except Exception:
        pass
    return str(value)

def _format_df_for_display(df: pd.DataFrame, digits: int = 4) -> pd.DataFrame:
    """Round numeric columns only for Gradio readability."""
    if df.empty:
        return df
    out = df.copy()
    for col in out.columns:
        if pd.api.types.is_numeric_dtype(out[col]):
            out[col] = out[col].round(digits)
    return out

def _status_text(completed: subprocess.CompletedProcess[str], output_dir: Path,
                 sbr_raw: pd.DataFrame, symm_raw: pd.DataFrame) -> str:
    """Build a compact status string stored in the generated PDF."""
    stdout = completed.stdout or ""
    stderr = completed.stderr or ""
    if completed.returncode == 0:
        status = "Pipeline completed successfully.\n\n"
    else:
        status = "Pipeline finished with errors.\n\n"

    status += f"Output folder:\n{output_dir}\n\n"
    status += f"SBR rows found: {len(sbr_raw)}\n"
    status += f"Symmetry rows found: {len(symm_raw)}\n\n"
    status += "Terminal output:\n"
    status += stdout[-4000:] if stdout else "(no standard output)"

    if stderr:
        status += "\n\nWarnings / errors:\n"
        status += stderr[-4000:]

    return status

def _find_resampled_dat(output_dir: Path) -> Path | None:
    """Find the registered/resampled DaT image generated by the pipeline."""
    candidates = sorted(output_dir.glob("*_desc-resampled_dat.nii.gz"))
    if candidates:
        return candidates[0]
    candidates = sorted(output_dir.glob("*_dat.nii.gz"))
    return candidates[0] if candidates else None

def _load_nifti_array(path: Path) -> np.ndarray:
    """Load a NIfTI image as a finite 3D float array."""
    arr = np.asarray(nib.load(str(path)).get_fdata(), dtype=np.float32)
    arr = np.squeeze(arr)
    if arr.ndim > 3:
        arr = arr[..., 0]
    arr = np.nan_to_num(arr, nan=0.0, posinf=0.0, neginf=0.0)
    return arr

def _robust_normalize(arr: np.ndarray, lower: float = 1, upper: float = 99) -> np.ndarray:
    """Normalize an array to [0, 1] using robust percentiles for visualization."""
    arr = np.asarray(arr, dtype=np.float32)
    finite = arr[np.isfinite(arr)]
    if finite.size == 0:
        return np.zeros_like(arr, dtype=np.float32)

    lo, hi = np.percentile(finite, [lower, upper])
    if hi <= lo:
        hi = float(np.max(finite))
        lo = float(np.min(finite))
    if hi <= lo:
        return np.zeros_like(arr, dtype=np.float32)

    return np.clip((arr - lo) / (hi - lo), 0, 1)

def _slice2d(arr: np.ndarray, axis: int, index: int) -> np.ndarray:
    """Extract and rotate one 2D slice for display."""
    index = int(np.clip(index, 0, arr.shape[axis] - 1))
    sl = np.take(arr, index, axis=axis)
    return np.rot90(sl)

def _resize_like(image: np.ndarray, target_shape: tuple[int, int]) -> np.ndarray:
    """Resize a 2D image for visualization only."""
    if image.shape == target_shape:
        return image
    try:
        from skimage.transform import resize
        return resize(
            image,
            target_shape,
            preserve_range=True,
            anti_aliasing=True,
        ).astype(np.float32)
    except Exception:
        out = np.zeros(target_shape, dtype=np.float32)
        min0 = min(target_shape[0], image.shape[0])
        min1 = min(target_shape[1], image.shape[1])
        out[:min0, :min1] = image[:min0, :min1]
        return out

def _dat_center_indices(dat: np.ndarray) -> np.ndarray:
    """Choose display slices around the high-uptake DaT region."""
    if dat.size == 0 or np.max(dat) <= 0:
        return np.asarray(dat.shape) // 2

    threshold = np.percentile(dat[dat > 0], 95) if np.any(dat > 0) else np.percentile(dat, 95)
    coords = np.argwhere(dat >= threshold)
    if coords.size == 0:
        return np.asarray(dat.shape) // 2

    return np.round(np.median(coords, axis=0)).astype(int)

def _create_overlay_gallery(mri_path: Path, output_dir: Path, run_dir: Path) -> list[tuple[str, str]]:
    """Create axial/coronal/sagittal MRI-DaT overlay images for the Gradio gallery."""
    dat_path = _find_resampled_dat(output_dir)
    if dat_path is None:
        return []

    mri = _load_nifti_array(mri_path)
    dat = _load_nifti_array(dat_path)

    if mri.ndim != 3 or dat.ndim != 3:
        return []

    display_dir = run_dir / "display"
    display_dir.mkdir(exist_ok=True)

    dat_center = _dat_center_indices(dat)
    views = [
        ("Axial", 2),
        ("Coronal", 1),
        ("Sagittal", 0),
    ]

    gallery: list[tuple[str, str]] = []
    for view_name, axis in views:
        dat_idx = int(dat_center[axis])
        mri_idx = int(round(dat_idx / max(dat.shape[axis] - 1, 1) * max(mri.shape[axis] - 1, 1)))

        mri_slice = _robust_normalize(_slice2d(mri, axis, mri_idx))
        dat_slice = _robust_normalize(_slice2d(dat, axis, dat_idx), lower=5, upper=99.5)
        dat_slice = _resize_like(dat_slice, mri_slice.shape)

        fig, axes = plt.subplots(1, 3, figsize=(10, 3.4), facecolor="white")
        for ax in axes:
            ax.axis("off")

        axes[0].imshow(mri_slice, cmap="gray")
        axes[0].set_title("MRI / T1w", fontsize=10)

        axes[1].imshow(dat_slice, cmap="hot")
        axes[1].set_title("Registered DaTSCAN", fontsize=10)

        axes[2].imshow(mri_slice, cmap="gray")
        masked_dat = np.ma.masked_where(dat_slice <= 0.05, dat_slice)
        axes[2].imshow(masked_dat, cmap="hot", alpha=0.55)
        axes[2].set_title("Overlay", fontsize=10)

        fig.tight_layout()
        out_path = display_dir / f"overlay_{view_name.lower()}.png"
        fig.savefig(out_path, dpi=170, bbox_inches="tight")
        plt.close(fig)

        gallery.append((str(out_path), view_name))

    return gallery

def _create_overlay_panel(
    mri_path: Path,
    output_dir: Path,
    run_dir: Path,
) -> str | None:
    """Create one compact 3x3 panel with axial/coronal/sagittal views.

    Rows:
        Axial, Coronal, Sagittal

    Columns:
        MRI / T1w, Registered DaTSCAN, Overlay
    """
    dat_path = _find_resampled_dat(output_dir)
    if dat_path is None:
        return None

    mri = _load_nifti_array(mri_path)
    dat = _load_nifti_array(dat_path)

    if mri.ndim != 3 or dat.ndim != 3:
        return None

    display_dir = run_dir / "display"
    display_dir.mkdir(exist_ok=True)

    dat_center = _dat_center_indices(dat)

    views = [
        ("Axial", 2),
        ("Coronal", 1),
        ("Sagittal", 0),
    ]

    panel_data = []

    for view_name, axis in views:
        dat_idx = int(dat_center[axis])

        mri_idx = int(
            round(
                dat_idx
                / max(dat.shape[axis] - 1, 1)
                * max(mri.shape[axis] - 1, 1)
            )
        )

        mri_slice = _robust_normalize(
            _slice2d(mri, axis, mri_idx)
        )

        dat_slice = _robust_normalize(
            _slice2d(dat, axis, dat_idx),
            lower=5,
            upper=99.5,
        )

        dat_slice = _resize_like(
            dat_slice,
            mri_slice.shape,
        )

        masked_dat = np.ma.masked_where(
            dat_slice <= 0.05,
            dat_slice,
        )

        panel_data.append(
            {
                "view_name": view_name,
                "mri": mri_slice,
                "dat": dat_slice,
                "overlay_mri": mri_slice,
                "overlay_dat": masked_dat,
            }
        )

    fig, axes = plt.subplots(
        3,
        3,
        figsize=(12.5, 12.0),
        facecolor="white",
    )

    col_titles = [
        "MRI / T1w",
        "Registered DaTSCAN",
        "Overlay",
    ]

    for col, title in enumerate(col_titles):
        axes[0, col].set_title(
            title,
            fontsize=18,
            pad=10,
        )

    for row, item in enumerate(panel_data):
        axes[row, 0].imshow(
            item["mri"],
            cmap="gray",
        )
        axes[row, 1].imshow(
            item["dat"],
            cmap="hot",
        )

        axes[row, 2].imshow(
            item["overlay_mri"],
            cmap="gray",
        )
        axes[row, 2].imshow(
            item["overlay_dat"],
            cmap="hot",
            alpha=0.55,
        )

        for col in range(3):
            axes[row, col].axis("off")

        axes[row, 0].set_ylabel(
            item["view_name"],
            fontsize=15,
            rotation=90,
            labelpad=18,
            va="center",
        )

    fig.subplots_adjust(
        left=0.06,
        right=0.985,
        top=0.95,
        bottom=0.035,
        wspace=0.04,
        hspace=0.08,
    )

    out_path = display_dir / "overlay_panel.png"
    fig.savefig(
        out_path,
        dpi=180,
        bbox_inches="tight",
        pad_inches=0.03,
    )
    plt.close(fig)

    return str(out_path)

def _create_single_slice_image(source_path: Path, run_dir: Path, name: str, cmap: str = "gray") -> Path | None:
    """Create one axial preview image from an input NIfTI file."""
    try:
        arr = _load_nifti_array(source_path)
        if arr.ndim != 3:
            return None
        idx = _dat_center_indices(arr)[2] if name.lower().startswith("dat") else arr.shape[2] // 2
        sl = _robust_normalize(_slice2d(arr, 2, idx), lower=1, upper=99)
        out_dir = run_dir / "display"
        out_dir.mkdir(exist_ok=True)
        out_path = out_dir / f"preview_{name}.png"

        fig, ax = plt.subplots(figsize=(3.2, 3.2), facecolor="black")
        ax.imshow(sl, cmap=cmap)
        ax.axis("off")
        fig.savefig(out_path, dpi=180, bbox_inches="tight", pad_inches=0)
        plt.close(fig)
        return out_path
    except Exception:
        return None

