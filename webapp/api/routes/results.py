from __future__ import annotations

from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse

from webapp.api.config import JOBS_DIR
from webapp.api.result_utils import prepare_job_results
from webapp.common.job_storage import read_meta


router = APIRouter(
    prefix="/api/jobs",
    tags=["Results"],
)


def _load_completed_job(job_id: str) -> tuple[dict, dict]:
    """Load one completed job and prepare its display/report artifacts."""
    job_dir = JOBS_DIR / job_id
    meta_path = job_dir / "meta.json"

    if not meta_path.exists():
        raise HTTPException(status_code=404, detail="Job not found")

    meta = read_meta(meta_path)

    if meta.get("status") != "completed":
        raise HTTPException(
            status_code=409,
            detail=f"Job is not completed. Current status: {meta.get('status', 'unknown')}",
        )

    try:
        results = prepare_job_results(job_dir, meta)
    except FileNotFoundError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Could not prepare DARQ results: {exc}",
        ) from exc

    return meta, results


@router.get("/{job_id}/results")
def get_job_results(job_id: str) -> dict:
    """Return the same DARQ result tables and artifact URLs used by Gradio."""
    _, results = _load_completed_job(job_id)

    return {
        "job_id": results["job_id"],
        "subject_id": results["subject_id"],
        "sbr": results["sbr"],
        "symmetry": results["symmetry"],
        "overlay_url": results["overlay_url"],
        "pdf_url": results["pdf_url"],
    }


@router.get("/{job_id}/overlay-panel")
def get_overlay_panel(job_id: str) -> FileResponse:
    """Serve the exact overlay panel generated by the existing Python code."""
    _, results = _load_completed_job(job_id)

    return FileResponse(
        path=results["overlay_path"],
        media_type="image/png",
    )


@router.get("/{job_id}/report")
def get_pdf_report(job_id: str) -> FileResponse:
    """Serve the exact DARQ PDF generated by the existing Python report code."""
    _, results = _load_completed_job(job_id)

    return FileResponse(
        path=results["pdf_path"],
        media_type="application/pdf",
        filename="DARQ_report.pdf",
    )
