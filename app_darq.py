def _df_rows_for_pdf(df: pd.DataFrame, max_rows: int | None = None) -> tuple[list[str], list[list[str]]]:
    """Convert a DataFrame to string rows for matplotlib table rendering."""
    if df.empty:
        return ["No data"], [["No data available"]]

    display_df = df.copy()
    if max_rows is not None:
        display_df = display_df.head(max_rows)

    columns = [str(c) for c in display_df.columns]
    rows = []
    for _, row in display_df.iterrows():
        rows.append([_format_number(v) for v in row.values])
    return columns, rows


def _draw_table(
    ax: plt.Axes,
    df: pd.DataFrame,
    title: str,
    max_rows: int | None = None,
    font_size: int = 7,
    scale_y: float = 1.2,
) -> None:
    """Draw a DataFrame on a matplotlib axis."""
    ax.axis("off")
    ax.set_title(title, loc="left", fontsize=11, fontweight="bold", pad=10)

    columns, rows = _df_rows_for_pdf(df, max_rows=max_rows)
    table = ax.table(
        cellText=rows,
        colLabels=columns,
        loc="center",
        cellLoc="center",
        colLoc="center",
    )
    table.auto_set_font_size(False)
    table.set_fontsize(font_size)
    table.scale(1, scale_y)

    for (r, c), cell in table.get_celld().items():
        if r == 0:
            cell.set_facecolor(REPORT_BLUE)
            cell.set_text_props(color="white", weight="bold")
        elif r % 2 == 0:
            cell.set_facecolor("#f1f1f1")
        else:
            cell.set_facecolor("white")


def _mean_rows_from_sbr(raw_sbr: pd.DataFrame) -> pd.DataFrame:
    """Extract aggregate=mean rows directly from the backend SBR TSV."""
    if raw_sbr.empty:
        return pd.DataFrame()

    df = raw_sbr.copy()
    if "aggregate" in df.columns:
        df = df[df["aggregate"] == "mean"].copy()

    hemi_order = {"R": 0, "L": 1, "Both": 2}
    if "hemi" in df.columns:
        df["_order"] = df["hemi"].map(hemi_order).fillna(99)
        df = df.sort_values("_order").drop(columns=["_order"])

    return df


def _dat_biomarker_pdf_table(raw_sbr: pd.DataFrame) -> pd.DataFrame:
    """Build an SBR table from backend mean uptake values.

    SBR = regional mean uptake / occipital mean uptake - 1.
    """
    mean_df = _mean_rows_from_sbr(raw_sbr)
    if mean_df.empty:
        return pd.DataFrame(columns=["Region", "Right SBR", "Left SBR", "Bilateral SBR"])

    def get_val(hemi: str, col: str):
        if "hemi" not in mean_df.columns or col not in mean_df.columns:
            return np.nan
        rows = mean_df[mean_df["hemi"] == hemi]
        return rows.iloc[0][col] if not rows.empty else np.nan

    def sbr(hemi: str, region_col: str):
        region_value = get_val(hemi, region_col)
        occ_value = get_val(hemi, "dat_occ")
        if pd.isna(region_value) or pd.isna(occ_value) or occ_value == 0:
            return np.nan
        return region_value / occ_value - 1

    mapping = {
        "Striatum": "dat_str",
        "Caudate": "dat_cau",
        "Putamen": "dat_put",
    }

    rows = []
    for region, col in mapping.items():
        rows.append({
            "Region": region,
            "Right SBR": sbr("R", col),
            "Left SBR": sbr("L", col),
            "Bilateral SBR": sbr("Both", col),
        })

    return pd.DataFrame(rows)

def _symmetry_pdf_table(raw_symm: pd.DataFrame) -> pd.DataFrame:
    """Build a compact symmetry table using aggregate=mean rows from *_symm.tsv.

    """
    if raw_symm.empty:
        return pd.DataFrame(columns=["Metric", "Region", "Right", "Left", "Bilateral"])

    df = raw_symm.copy()

    if "aggregate" in df.columns:
        df = df[df["aggregate"] == "mean"].copy()

    def get_val(metric: str, hemi: str, col: str):
        needed = {"metric", "hemi", col}
        if not needed.issubset(df.columns):
            return np.nan

        rows = df[(df["metric"] == metric) & (df["hemi"] == hemi)]
        return rows.iloc[0][col] if not rows.empty else np.nan

    rows = []
    for metric in ["lncc", "l2"]:
        for region, col in {
            "Caudate": "dat_cau",
            "Putamen": "dat_put",
        }.items():
            rows.append({
                "Metric": metric,
                "Region": region,
                "Right": get_val(metric, "R", col),
                "Left": get_val(metric, "L", col),
                "Bilateral": get_val(metric, "Both", col),
            })

    return pd.DataFrame(rows)

def _quality_control(completed: subprocess.CompletedProcess[str], raw_sbr: pd.DataFrame) -> str:
    """Return simple execution quality label."""
    if completed.returncode == 0 and not raw_sbr.empty:
        return "A"
    if completed.returncode == 0:
        return "B"
    return "C"


def _add_image_to_fig(fig: plt.Figure, img_path: str | Path | None,
                      rect: list[float], title: str | None = None,
                      title_color: str = "black") -> None:
    """Add an image to a figure in a fixed rectangle."""
    ax = fig.add_axes(rect)
    ax.axis("off")
    if img_path is None or not Path(img_path).exists():
        ax.text(0.5, 0.5, "No image", ha="center", va="center", fontsize=10)
    else:
        image = plt.imread(str(img_path))
        ax.imshow(image)
    if title:
        ax.set_title(title, fontsize=9, color=title_color, pad=4)


