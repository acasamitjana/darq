def run_darq_report(
    dat_file: str | None,
    mri_file: str | None,
    seg_file: str | None,
    subject_id: str,
    progress: gr.Progress = gr.Progress(track_tqdm=True),
):
    """Run the DARQ pipeline and return complete tables, images and PDF."""
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_subject = (subject_id or "subject").strip().replace(" ", "_") or "subject"
    run_dir = RUNS_DIR / f"run_{timestamp}_{safe_subject}"
    input_dir = run_dir / "inputs"
    output_dir = run_dir / "output"
    input_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    progress(0.05, desc="Preparing files")
    pipeline_script = _find_pipeline_script()
    dat_path = _copy_uploaded_file(dat_file, input_dir, "datscan")
    mri_path = _copy_uploaded_file(mri_file, input_dir, "T1w")
    seg_path = _copy_uploaded_file(seg_file, input_dir, "synthseg")

    command = [
        sys.executable,
        str(pipeline_script),
        "--dat",
        str(dat_path),
        "--mri",
        str(mri_path),
        "--seg",
        str(seg_path),
        "--o",
        str(output_dir),
        "--opt_str",
        DEFAULT_OPTIMIZER,
    ]

    if FORCE_RECOMPUTE:
        command.append("--force")
    if USE_CPU:
        command.append("--cpu")

    env = os.environ.copy()
    env["PYTHONPATH"] = str(ROOT_DIR)

    progress(0.20, desc="Running DARQ pipeline")
    completed = subprocess.run(
        command,
        cwd=str(ROOT_DIR),
        env=env,
        text=True,
        capture_output=True,
        timeout=None,
    )

    progress(0.70, desc="Reading backend tables")
    sbr_raw = _read_first_tsv(output_dir, "*_sbr.tsv")
    symm_raw = _read_first_tsv(output_dir, "*_symm.tsv")

    if completed.returncode != 0:
        status = _status_text(completed, output_dir, sbr_raw, symm_raw)
        raise gr.Error(status)

    progress(0.82, desc="Creating image overlays")
    overlay_gallery = _create_overlay_gallery(mri_path, output_dir, run_dir)

    progress(0.92, desc="Creating PDF report")
    status = _status_text(completed, output_dir, sbr_raw, symm_raw)
    pdf_path = _create_pdf_report(
        run_dir=run_dir,
        subject_id=safe_subject,
        dat_input_path=dat_path,
        mri_input_path=mri_path,
        raw_sbr=sbr_raw,
        raw_symm=symm_raw,
        overlay_gallery=overlay_gallery,
        completed=completed,
        status_text=status,
    )

    progress(1.0, desc="Finished")

    return (
        _format_df_for_display(sbr_raw),
        _format_df_for_display(symm_raw),
        overlay_gallery,
        str(pdf_path) if pdf_path else None,
    )


