def _find_pipeline_script() -> Path:
    """Return the expected pipeline script path."""
    candidates = [
        ROOT_DIR / "scripts" / "dat2mri.py",
        ROOT_DIR / "dat2mri.py",
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate

    raise FileNotFoundError(
        "No pipeline script was found. Expected scripts/dat2mri.py or dat2mri.py "
        "in the project root."
    )


def _check_nifti_extension(path: Path) -> None:
    """Check that the uploaded file looks like a NIfTI image."""
    if not (path.name.endswith(".nii") or path.name.endswith(".nii.gz")):
        raise ValueError(
            f"The file {path.name} does not seem to be a valid NIfTI file. "
            "It must end with .nii or .nii.gz."
        )


def _copy_uploaded_file(uploaded_path: str | None, destination_dir: Path, name: str) -> Path:
    """Copy a Gradio-uploaded file to a stable run folder."""
    if uploaded_path is None:
        raise ValueError(f"Missing uploaded file: {name}")

    source = Path(uploaded_path)
    if not source.exists():
        raise FileNotFoundError(f"Uploaded file not found: {source}")

    _check_nifti_extension(source)

    suffix = ".nii.gz" if source.name.endswith(".nii.gz") else source.suffix
    destination = destination_dir / f"{name}{suffix}"
    shutil.copy2(source, destination)
    return destination


def _read_first_tsv(output_dir: Path, pattern: str) -> pd.DataFrame:
    """Read the first TSV matching a pattern, or return an empty table."""
    matches = sorted(output_dir.glob(pattern))
    if not matches:
        return pd.DataFrame()
    return pd.read_csv(matches[0], sep="\t")


def _format_number(value, digits: int = 4) -> str:
    """Format numbers for report tables without changing the underlying values."""
    try:
        if pd.isna(value):
            return "—"
        if isinstance(value, (float, np.floating)):
            return f"{float(value):.{digits}f}"
        if isinstance(value, (int, np.integer)):
            return str(int(value))
    except Exception:
        pass
    return str(value)


def _format_df_for_display(df: pd.DataFrame, digits: int = 4) -> pd.DataFrame:
    """Round numeric columns only for Gradio readability."""
    if df.empty:
        return df
    out = df.copy()
    for col in out.columns:
        if pd.api.types.is_numeric_dtype(out[col]):
            out[col] = out[col].round(digits)
    return out


def _status_text(completed: subprocess.CompletedProcess[str], output_dir: Path,
                 sbr_raw: pd.DataFrame, symm_raw: pd.DataFrame) -> str:
    """Build a compact status string stored in the generated PDF."""
    stdout = completed.stdout or ""
    stderr = completed.stderr or ""
    if completed.returncode == 0:
        status = "Pipeline completed successfully.\n\n"
    else:
        status = "Pipeline finished with errors.\n\n"

    status += f"Output folder:\n{output_dir}\n\n"
    status += f"SBR rows found: {len(sbr_raw)}\n"
    status += f"Symmetry rows found: {len(symm_raw)}\n\n"
    status += "Terminal output:\n"
    status += stdout[-4000:] if stdout else "(no standard output)"

    if stderr:
        status += "\n\nWarnings / errors:\n"
        status += stderr[-4000:]

    return status


